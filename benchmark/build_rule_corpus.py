"""
build_rule_corpus.py — assemble a demonstration corpus in which all 15 rules fire.

Two evidence sources already exist in this repository, each covering a disjoint
part of the rule set:

  * benchmark/real_world/           the 96-repo quasi-random study, which
                                    exercised the seven common rules
                                    (R01, R03, R05-R09). Sources in
                                    realworld_targets/.
  * benchmark/rule_coverage/        the pattern-searched coverage study, which
                                    exercised the eight rarer rules
                                    (R02, R04, R10-R15). Sources in
                                    evidence_archive/, commit-pinned.

This script re-scans both with the *current* scanner (rather than trusting the
recorded July figures, which predate the tier 2/3 scanner rewrite), then selects
a corpus that covers all 15 rules: a greedy set cover for the mandatory core,
padded to --size by descending rule count.

IMPORTANT — what this corpus is and is not. The rule_coverage half was found by
searching for the pattern each rule detects, so the sample is biased toward
positives by construction. This corpus demonstrates that every rule fires on
genuine third-party code. It is NOT a precision sample and no precision figure
may be computed from it; that role belongs to benchmark/real_world/ and the
held-out set in benchmark/heldout/.

Usage:
    python benchmark/build_rule_corpus.py             # 30 repos
    python benchmark/build_rule_corpus.py --size 20
"""

import argparse
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from jwtcheck.rules import RULES  # noqa: E402
from jwtcheck.scanner import Scanner  # noqa: E402

MANIFEST = os.path.join(HERE, "rule_coverage", "evidence_manifest.json")
REALWORLD_DIR = os.path.join(ROOT, "realworld_targets")
OUT = os.path.join(HERE, "rule_corpus.json")
OUT_TEX = os.path.join(HERE, "rule_corpus.tex")


def tex_escape(s):
    return s.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&")


def write_tex(coverage, chosen):
    """Emit the Chapter 5 coverage table as a standalone, \\input-able fragment."""
    by_rule = collections.defaultdict(list)
    for repo in chosen:
        for rule in coverage[repo]:
            by_rule[rule].append(repo)

    lines = [
        "% Generated by benchmark/build_rule_corpus.py -- do not edit by hand.",
        "% Demonstration corpus only: the rule-coverage half was found by "
        "searching for",
        "% each rule's pattern, so no precision figure may be derived from this "
        "table.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        r"\caption{All fifteen JWTCheck rules exercised by third-party public "
        r"code. Repository counts are within the " + str(len(chosen)) +
        r"-project demonstration corpus.}",
        r"\label{tab:rule-corpus}",
        r"\begin{tabular}{lllrl}",
        r"\hline",
        r"\textbf{Rule} & \textbf{Severity} & \textbf{Detects} & "
        r"\textbf{Repos} & \textbf{Example project} \\",
        r"\hline",
    ]
    for rid in sorted(RULES):
        repos = by_rule.get(rid, [])
        example = tex_escape(repos[0]) if repos else "---"
        lines.append(
            f"{rid} & {RULES[rid].severity.title()} & "
            f"\\texttt{{{tex_escape(RULES[rid].name)}}} & {len(repos)} & "
            f"\\texttt{{\\footnotesize {example}}} \\\\"
        )
    lines += [r"\hline", r"\end{tabular}", r"\end{table}", ""]

    with open(OUT_TEX, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def scan_evidence_archive(scanner):
    """Re-scan each commit-pinned evidence file. Returns repo -> {rule: [permalink]}."""
    with open(MANIFEST, encoding="utf-8") as fh:
        entries = json.load(fh)

    hits = collections.defaultdict(lambda: collections.defaultdict(list))
    missing = []
    for e in entries:
        path = os.path.join(ROOT, e["local_copy"])
        if not os.path.isfile(path):
            missing.append(e["local_copy"])
            continue
        for f in scanner.scan_file(path):
            hits[e["repo"]][f.rule_id].append(f"{e['permalink']}#L{f.line}")
    return hits, missing


def scan_realworld(scanner):
    """Re-scan the cloned 96-repo sample. Returns repo -> {rule: [path:line]}."""
    hits = collections.defaultdict(lambda: collections.defaultdict(list))
    if not os.path.isdir(REALWORLD_DIR):
        return hits
    for name in sorted(os.listdir(REALWORLD_DIR)):
        repo_dir = os.path.join(REALWORLD_DIR, name)
        if not os.path.isdir(repo_dir):
            continue
        repo = name.replace("__", "/", 1)
        for f in scanner.scan_directory(repo_dir, recursive=True, exclude_tests=True):
            rel = os.path.relpath(f.filepath, repo_dir).replace(os.sep, "/")
            hits[repo][f.rule_id].append(f"{rel}:{f.line}")
    return hits


def select(coverage, size):
    """Greedy set cover for all 15 rules, then pad to `size` by rule count."""
    need, chosen = set(RULES), []
    while need:
        best = max(coverage, key=lambda r: (len(set(coverage[r]) & need), len(coverage[r])))
        gained = set(coverage[best]) & need
        if not gained:
            break
        chosen.append(best)
        need -= gained

    rest = sorted((r for r in coverage if r not in chosen),
                  key=lambda r: (-len(coverage[r]),
                                 -sum(len(v) for v in coverage[r].values()), r))
    chosen += rest[:max(0, size - len(chosen))]
    return chosen, need


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=30,
                    help="Target corpus size (default 30). The set cover is "
                         "always included even if it exceeds this.")
    args = ap.parse_args()

    scanner = Scanner()
    print("Re-scanning commit-pinned evidence archive ...")
    archive_hits, missing = scan_evidence_archive(scanner)
    print(f"  {len(archive_hits)} repos with findings"
          + (f", {len(missing)} archived files absent" if missing else ""))

    print("Re-scanning the 96-repo real-world sample ...")
    rw_hits = scan_realworld(scanner)
    print(f"  {len(rw_hits)} repos with findings")

    coverage = collections.defaultdict(lambda: collections.defaultdict(list))
    source = {}
    for repo, rules in archive_hits.items():
        source[repo] = "rule_coverage (pattern-searched, commit-pinned)"
        for rule, locs in rules.items():
            coverage[repo][rule].extend(locs)
    for repo, rules in rw_hits.items():
        source.setdefault(repo, "real_world (quasi-random sample)")
        for rule, locs in rules.items():
            coverage[repo][rule].extend(locs)

    union = set().union(*(set(v) for v in coverage.values())) if coverage else set()
    print(f"\nUnion across both sources: {len(union)}/15 rules "
          f"({', '.join(sorted(union))})")
    absent = sorted(set(RULES) - union)
    if absent:
        print(f"NOT reproducible under the current scanner: {', '.join(absent)}")

    chosen, uncovered = select(coverage, args.size)
    corpus_rules = set().union(*(set(coverage[r]) for r in chosen))

    out = {
        "purpose": "demonstration corpus in which all 15 rules fire",
        "not_a_precision_sample": (
            "The rule_coverage half was found by searching for the pattern each "
            "rule detects. No precision or recall figure may be derived from it."
        ),
        "scanner_commit": os.popen("git -C \"%s\" rev-parse --short HEAD" % ROOT).read().strip(),
        "size": len(chosen),
        "rules_covered": sorted(corpus_rules),
        "repos": [
            {
                "repo": r,
                "source": source[r],
                "rules": sorted(coverage[r]),
                "n_findings": sum(len(v) for v in coverage[r].values()),
                "evidence": {k: v[:3] for k, v in sorted(coverage[r].items())},
            }
            for r in chosen
        ],
    }
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2)

    write_tex(coverage, chosen)

    print(f"\nCorpus: {len(chosen)} repos covering "
          f"{len(corpus_rules)}/15 rules -> {os.path.relpath(OUT, ROOT)}"
          f" + {os.path.relpath(OUT_TEX, ROOT)}")
    for r in chosen[:12]:
        print(f"   {r:<55} {','.join(sorted(coverage[r]))}")
    if len(chosen) > 12:
        print(f"   ... and {len(chosen) - 12} more")
    if uncovered:
        print(f"\nWARNING: no repo available for {', '.join(sorted(uncovered))}")


if __name__ == "__main__":
    main()
