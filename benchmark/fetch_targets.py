"""
fetch_targets.py — sample real-world Python repositories that use PyJWT.

Uses GitHub code search (via the authenticated `gh` CLI) to find public,
non-fork repositories containing genuine PyJWT calls (jwt.decode / jwt.encode /
import jwt). The unique repo list is written to benchmark/real_world_repos.txt,
which run_real_world.py then clones and scans.

Sampling repositories from code search (rather than hand-picking) makes the
real-world evaluation reproducible and defensible: the corpus is "public GitHub
repositories matching PyJWT usage", not a curated selection.

Usage:
    python benchmark/fetch_targets.py --target 60
Requires: gh CLI, authenticated (gh auth status).
"""

import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "real_world_repos.txt")

# Code-search queries that indicate real PyJWT usage.
QUERIES = [
    "jwt.decode",
    "jwt.encode",
    "from jwt import",
    "PyJWKClient",
]


def search(query: str, limit: int) -> list:
    """Return [nameWithOwner, ...] from one gh code-search query."""
    try:
        proc = subprocess.run(
            ["gh", "search", "code", query, "--language=python",
             f"--limit={limit}", "--json", "repository"],
            capture_output=True, text=True, timeout=120,
        )
        data = json.loads(proc.stdout or "[]")
    except (subprocess.SubprocessError, json.JSONDecodeError) as exc:
        print(f"  [warn] query '{query}' failed: {exc}", file=sys.stderr)
        return []
    repos = []
    for rec in data:
        repo = rec.get("repository", {})
        if repo.get("isFork") or repo.get("isPrivate"):
            continue
        name = repo.get("nameWithOwner")
        if name:
            repos.append(name)
    return repos


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target", type=int, default=60,
                    help="Desired number of unique repositories (default 60).")
    ap.add_argument("--per-query", type=int, default=100,
                    help="Max results per search query (default 100).")
    args = ap.parse_args()

    seen = []
    seen_set = set()
    for q in QUERIES:
        print(f"Searching: {q!r} ...")
        for name in search(q, args.per_query):
            if name not in seen_set:
                seen_set.add(name)
                seen.append(name)
        print(f"  unique so far: {len(seen)}")
        if len(seen) >= args.target:
            break

    seen = seen[:max(args.target, len(seen))]
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# Real-world target repositories (sampled from GitHub code "
                 "search for PyJWT usage)\n")
        fh.write(f"# Generated by fetch_targets.py — {len(seen)} repositories\n")
        for name in seen:
            fh.write(name + "\n")

    print(f"\nWrote {len(seen)} repositories to {OUT}")
    if len(seen) < args.target:
        print(f"(target was {args.target}; code search returned fewer — "
              "rerun later or add more queries)")


if __name__ == "__main__":
    main()
